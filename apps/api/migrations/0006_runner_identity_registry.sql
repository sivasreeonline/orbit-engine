BEGIN;

-- Provider-neutral runner registry. Store verified issuer/subject bindings,
-- never bearer tokens, client secrets, private keys or certificate private data.
CREATE TABLE IF NOT EXISTS runner_pools (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  pool_key varchar(96) NOT NULL UNIQUE
    CHECK (pool_key ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  status varchar(16) NOT NULL DEFAULT 'ACTIVE'
    CHECK (status IN ('ACTIVE', 'DISABLED')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS runner_identities (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  runner_id varchar(128) NOT NULL UNIQUE
    CHECK (runner_id ~ '^[A-Za-z0-9._:-]{1,128}$'),
  pool_id uuid NOT NULL
    REFERENCES runner_pools(id) ON DELETE RESTRICT,
  identity_issuer varchar(512) NOT NULL
    CHECK (length(btrim(identity_issuer)) BETWEEN 1 AND 512),
  identity_subject varchar(512) NOT NULL
    CHECK (length(btrim(identity_subject)) BETWEEN 1 AND 512),
  status varchar(16) NOT NULL DEFAULT 'ACTIVE'
    CHECK (status IN ('ACTIVE', 'SUSPENDED', 'REVOKED')),
  scopes text[] NOT NULL
    CHECK (
      cardinality(scopes) BETWEEN 1 AND 3
      AND scopes <@ ARRAY[
        'dispatch:claim', 'dispatch:receipt', 'dispatch:retry'
      ]::text[]
    ),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  revoked_at timestamptz NULL,
  CONSTRAINT runner_identity_issuer_subject_uk
    UNIQUE (identity_issuer, identity_subject),
  CONSTRAINT runner_identity_revocation_timestamp_ck CHECK (
    (status = 'REVOKED' AND revoked_at IS NOT NULL)
    OR (status <> 'REVOKED' AND revoked_at IS NULL)
  )
);

CREATE INDEX IF NOT EXISTS idx_runner_identities_pool_status
  ON runner_identities (pool_id, status);

CREATE INDEX IF NOT EXISTS idx_runner_pools_status
  ON runner_pools (status, pool_key);

-- Lifecycle events are generated by database triggers, not caller-supplied
-- audit rows. They intentionally do not claim an operator identity; trusted
-- operator attribution requires a future authenticated administration path.
CREATE TABLE IF NOT EXISTS runner_identity_events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  runner_identity_id uuid NOT NULL
    REFERENCES runner_identities(id) ON DELETE RESTRICT,
  event_type varchar(24) NOT NULL
    CHECK (event_type IN ('REGISTERED', 'STATUS_CHANGED', 'SCOPES_CHANGED')),
  previous_status varchar(16) NULL,
  new_status varchar(16) NOT NULL
    CHECK (new_status IN ('ACTIVE', 'SUSPENDED', 'REVOKED')),
  previous_scopes text[] NULL,
  new_scopes text[] NOT NULL,
  occurred_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_runner_identity_events_identity_time
  ON runner_identity_events (runner_identity_id, occurred_at DESC, id);

CREATE OR REPLACE FUNCTION guard_runner_identity_write()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'runner identity records must be revoked, not deleted'
      USING ERRCODE = '55000';
  END IF;

  IF NEW.runner_id IS DISTINCT FROM OLD.runner_id
    OR NEW.pool_id IS DISTINCT FROM OLD.pool_id
    OR NEW.identity_issuer IS DISTINCT FROM OLD.identity_issuer
    OR NEW.identity_subject IS DISTINCT FROM OLD.identity_subject
    OR NEW.created_at IS DISTINCT FROM OLD.created_at
    OR NEW.id IS DISTINCT FROM OLD.id THEN
    RAISE EXCEPTION 'runner identity binding is immutable'
      USING ERRCODE = '55000';
  END IF;

  IF OLD.status = 'REVOKED' THEN
    RAISE EXCEPTION 'revoked runner identity is terminal'
      USING ERRCODE = '55000';
  END IF;

  IF NEW.status = 'REVOKED' THEN
    NEW.revoked_at := clock_timestamp();
  ELSE
    NEW.revoked_at := NULL;
  END IF;

  NEW.updated_at := clock_timestamp();
  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS trg_guard_runner_identity_write ON runner_identities;
CREATE TRIGGER trg_guard_runner_identity_write
BEFORE UPDATE OR DELETE ON runner_identities
FOR EACH ROW EXECUTE FUNCTION guard_runner_identity_write();

CREATE OR REPLACE FUNCTION guard_runner_pool_write()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'runner pools cannot be deleted'
      USING ERRCODE = '55000';
  END IF;
  IF NEW.id IS DISTINCT FROM OLD.id
    OR NEW.pool_key IS DISTINCT FROM OLD.pool_key
    OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
    RAISE EXCEPTION 'runner pool identity is immutable'
      USING ERRCODE = '55000';
  END IF;
  NEW.updated_at := clock_timestamp();
  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS trg_guard_runner_pool_write ON runner_pools;
CREATE TRIGGER trg_guard_runner_pool_write
BEFORE UPDATE OR DELETE ON runner_pools
FOR EACH ROW EXECUTE FUNCTION guard_runner_pool_write();

CREATE OR REPLACE FUNCTION record_runner_identity_event()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO runner_identity_events (
      runner_identity_id, event_type, previous_status, new_status,
      previous_scopes, new_scopes
    ) VALUES (
      NEW.id, 'REGISTERED', NULL, NEW.status, NULL, NEW.scopes
    );
    RETURN NEW;
  END IF;

  IF NEW.status IS DISTINCT FROM OLD.status THEN
    INSERT INTO runner_identity_events (
      runner_identity_id, event_type, previous_status, new_status,
      previous_scopes, new_scopes
    ) VALUES (
      NEW.id, 'STATUS_CHANGED', OLD.status, NEW.status,
      OLD.scopes, NEW.scopes
    );
  END IF;

  IF NEW.scopes IS DISTINCT FROM OLD.scopes THEN
    INSERT INTO runner_identity_events (
      runner_identity_id, event_type, previous_status, new_status,
      previous_scopes, new_scopes
    ) VALUES (
      NEW.id, 'SCOPES_CHANGED', OLD.status, NEW.status,
      OLD.scopes, NEW.scopes
    );
  END IF;
  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS trg_record_runner_identity_event ON runner_identities;
CREATE TRIGGER trg_record_runner_identity_event
AFTER INSERT OR UPDATE ON runner_identities
FOR EACH ROW EXECUTE FUNCTION record_runner_identity_event();

CREATE OR REPLACE FUNCTION reject_runner_identity_event_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
  RAISE EXCEPTION 'runner identity lifecycle events are immutable'
    USING ERRCODE = '55000';
END;
$function$;

DROP TRIGGER IF EXISTS trg_runner_identity_event_immutable ON runner_identity_events;
CREATE TRIGGER trg_runner_identity_event_immutable
BEFORE UPDATE OR DELETE ON runner_identity_events
FOR EACH ROW EXECUTE FUNCTION reject_runner_identity_event_mutation();

